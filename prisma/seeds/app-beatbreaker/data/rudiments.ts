/**
 * The rudiments — seed data (Phase 10, D43).
 *
 * The forty Percussive Arts Society International Drum Rudiments, on six
 * shelves as PAS files them. Each is a bar or two on the snare alone, with
 * its sticking written under every note (`hands`, D44), so the chart prints
 * it and the 3D drummer plays it.
 *
 * **Written open, on the grids that exist.** There is no 32nd-note meter, so
 * a roll's diddles are two 16ths, the way a roll is first taught; the practice
 * session's climb takes it from open towards closed. Triplet rudiments are in
 * sextuplets (`4/4-6`), and a rudiment whose figure falls in threes is in 6/8
 * or 3/4. Where a rudiment alternates, one half (or one bar) leads right and
 * the next leads left.
 *
 * The snare: `s` tap · `S` accent · `f` flam · `d` drag · `z` buzz. A flam or
 * drag's grace notes are on the other hand, except where the hand is written
 * lower case: the single dragadiddle's drag is a double from the same stick.
 * Every entry is `fixed` (D45): all five layers play it whole.
 *
 * **Content, not code** (D13), like `library.ts` beside it: only the
 * `001-catalogue` seed unit reads this file.
 */

